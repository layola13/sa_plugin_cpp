#include <iostream>

int main() {
    int a = 17;
    int b = 5;
    std::cout << a + b << std::endl;
    std::cout << a - b << std::endl;
    std::cout << a * b << std::endl;
    std::cout << a / b << std::endl;
    std::cout << a % b << std::endl;
    std::cout << -a << std::endl;
    std::cout << (a + b) * 2 << std::endl;
    return 0;
}
